-- Catálogo: leitura pública apenas de produtos ativos. O admin vê tudo.
drop policy if exists "products public read" on public.products;
create policy "products public read"
  on public.products for select
  using (active or public.is_admin());

drop policy if exists "products admin write" on public.products;
create policy "products admin write"
  on public.products for all
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "variants public read" on public.variants;
create policy "variants public read"
  on public.variants for select
  using (
    public.is_admin()
    or exists (
      select 1 from public.products p
       where p.id = variants.product_id
         and p.active
    )
  );

drop policy if exists "variants admin write" on public.variants;
create policy "variants admin write"
  on public.variants for all
  using (public.is_admin())
  with check (public.is_admin());

-- Pedidos: ninguém cria pedido direto pela API (só pela função create_order).
-- Leitura e alteração de status são exclusivas do admin.
drop policy if exists "orders admin read" on public.orders;
create policy "orders admin read"
  on public.orders for select
  using (public.is_admin());

drop policy if exists "order_items admin read" on public.order_items;
create policy "order_items admin read"
  on public.order_items for select
  using (public.is_admin());

-- ----------------------------------------------------------------------------
-- Checkout · create_order
-- Valida itens e estoque, calcula frete e cria o pedido (status pending).
-- O estoque só é debitado quando o pagamento é confirmado (pay_order).
-- ----------------------------------------------------------------------------
create or replace function public.create_order(
  p_email     text,
  p_full_name text,
  p_address   text,
  p_items     jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_items    jsonb;
  v_subtotal integer := 0;
  v_shipping integer := 0;
  v_number   text;
  v_order_id bigint;
  v_created  timestamptz;
begin
  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Sua sacola está vazia.';
  end if;

  if coalesce(trim(p_email), '') !~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    raise exception 'Informe um e-mail válido.';
  end if;

  if length(coalesce(trim(p_full_name), '')) < 2 then
    raise exception 'Informe seu nome completo.';
  end if;

  if length(coalesce(trim(p_address), '')) < 8 then
    raise exception 'Informe o endereço de entrega.';
  end if;

  -- Agrupa itens repetidos para validar o estoque corretamente.
  select jsonb_agg(jsonb_build_object('variant_id', variant_id, 'quantity', quantity))
    into v_items
    from (
      select variant_id, sum(quantity)::int as quantity
        from jsonb_to_recordset(p_items) as x(variant_id bigint, quantity int)
       group by variant_id
    ) grouped;

  if v_items is null then
    raise exception 'Sua sacola está vazia.';
  end if;

  if exists (
    select 1
      from jsonb_to_recordset(v_items) as x(variant_id bigint, quantity int)
      left join public.variants v on v.id = x.variant_id
      left join public.products p on p.id = v.product_id
     where v.id is null
        or p.id is null
        or not p.active
        or x.quantity < 1
        or v.stock < x.quantity
  ) then
    raise exception 'Um dos produtos está indisponível ou sem estoque suficiente. Atualize sua sacola.';
  end if;

  select coalesce(sum(v.price_cents * x.quantity), 0)
    into v_subtotal
    from jsonb_to_recordset(v_items) as x(variant_id bigint, quantity int)
    join public.variants v on v.id = x.variant_id;

  v_shipping := case when v_subtotal >= 29900 then 0 else 2990 end;
  v_number := 'KM-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));

  insert into public.orders
    (number, email, full_name, address, subtotal_cents, shipping_cents,
     total_cents, currency, status, payment_provider)
  values
    (v_number, trim(p_email), trim(p_full_name), trim(p_address), v_subtotal,
     v_shipping, v_subtotal + v_shipping, 'brl', 'pending', 'mock')
  returning id, created_at into v_order_id, v_created;

  insert into public.order_items
    (order_id, variant_id, product_name, variant_name, sku, unit_price_cents, quantity)
  select v_order_id, v.id, p.name, v.name, v.sku, v.price_cents, x.quantity
    from jsonb_to_recordset(v_items) as x(variant_id bigint, quantity int)
    join public.variants v on v.id = x.variant_id
    join public.products p on p.id = v.product_id;

  return jsonb_build_object(
    'id', v_order_id,
    'number', v_number,
    'subtotal_cents', v_subtotal,
    'shipping_cents', v_shipping,
    'total_cents', v_subtotal + v_shipping,
    'currency', 'brl',
    'status', 'pending',
    'created_at', v_created
  );
end;
$$;

-- ----------------------------------------------------------------------------
-- Pagamento simulado · pay_order
-- p_outcome = 'success' | 'fail'. Em sucesso, baixa o estoque com trava.
-- ----------------------------------------------------------------------------
create or replace function public.pay_order(
  p_number  text,
  p_outcome text default 'success'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item  record;
begin
  select * into v_order
    from public.orders
   where number = p_number
   for update;

  if not found then
    raise exception 'Pedido não encontrado.';
  end if;

  if v_order.status = 'paid' then
    return jsonb_build_object('ok', true, 'status', 'paid', 'number', v_order.number);
  end if;

  if v_order.status <> 'pending' then
    raise exception 'Este pedido não está aguardando pagamento.';
  end if;

  if p_outcome = 'fail' then
    update public.orders set status = 'failed' where id = v_order.id;
    return jsonb_build_object('ok', true, 'status', 'failed', 'number', v_order.number);
  end if;

  for v_item in
    select * from public.order_items where order_id = v_order.id
  loop
    if v_item.variant_id is not null then
      update public.variants
         set stock = stock - v_item.quantity
       where id = v_item.variant_id
         and stock >= v_item.quantity;

      if not found then
        raise exception 'Estoque insuficiente para o item %.', v_item.sku;
      end if;
    end if;
  end loop;

  update public.orders
     set status = 'paid', paid_at = now()
   where id = v_order.id
  returning * into v_order;

  return jsonb_build_object(
    'ok', true,
    'status', 'paid',
    'number', v_order.number,
    'total_cents', v_order.total_cents,
    'paid_at', v_order.paid_at
  );
end;
$$;

-- ----------------------------------------------------------------------------
-- Consulta pública do status (sem dados pessoais) para a página de sucesso.
-- ----------------------------------------------------------------------------
create or replace function public.order_status(p_number text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
           'number', number,
           'status', status,
           'total_cents', total_cents,
           'shipping_cents', shipping_cents,
           'currency', currency,
           'created_at', created_at,
           'paid_at', paid_at
         )
    from public.orders
   where number = p_number;
$$;

-- ----------------------------------------------------------------------------
-- Admin · alterar status com ajuste de estoque
-- ----------------------------------------------------------------------------
create or replace function public.set_order_status(
  p_number text,
  p_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item  record;
begin
  if not public.is_admin() then
    raise exception 'Acesso negado.';
  end if;

  if p_status not in ('pending', 'paid', 'shipped', 'cancelled', 'failed') then
    raise exception 'Status inválido.';
  end if;

  select * into v_order
    from public.orders
   where number = p_number
   for update;

  if not found then
    raise exception 'Pedido não encontrado.';
  end if;

  if v_order.status = p_status then
    return jsonb_build_object('ok', true, 'status', p_status, 'number', v_order.number);
  end if;

  -- Evita transições que bagunçariam o estoque (ex.: paid → pending → paid).
  if not (
       (v_order.status = 'pending' and p_status in ('paid', 'cancelled', 'failed'))
    or (v_order.status = 'failed'  and p_status in ('pending', 'paid', 'cancelled'))
    or (v_order.status = 'paid'    and p_status in ('shipped', 'cancelled'))
    or (v_order.status = 'shipped' and p_status = 'cancelled')
  ) then
    raise exception 'Transição de status inválida: % → %.', v_order.status, p_status;
  end if;

  -- Cancelou um pedido pago/enviado: devolve o estoque.
  if p_status = 'cancelled' and v_order.status in ('paid', 'shipped') then
    for v_item in select * from public.order_items where order_id = v_order.id loop
      if v_item.variant_id is not null then
        update public.variants
           set stock = stock + v_item.quantity
         where id = v_item.variant_id;
      end if;
    end loop;
  end if;

  -- Marcou como pago manualmente: baixa o estoque.
  if p_status = 'paid' and v_order.status in ('pending', 'failed') then
    for v_item in select * from public.order_items where order_id = v_order.id loop
      if v_item.variant_id is not null then
        update public.variants
           set stock = stock - v_item.quantity
         where id = v_item.variant_id
           and stock >= v_item.quantity;

        if not found then
          raise exception 'Estoque insuficiente para o item %.', v_item.sku;
        end if;
      end if;
    end loop;
  end if;

  update public.orders
     set status = p_status,
         paid_at = case
                     when p_status = 'paid' then coalesce(paid_at, now())
                     else paid_at
                   end
   where id = v_order.id;

  return jsonb_build_object('ok', true, 'status', p_status, 'number', v_order.number);
end;
$$;

-- ----------------------------------------------------------------------------
-- Permissões
-- O Supabase já cria grants padrão, mas deixamos explícito para funcionar
-- mesmo se os defaults do projeto forem alterados.
-- ----------------------------------------------------------------------------
grant usage on schema public to anon, authenticated;

-- Catálogo: leitura pública; escrita apenas para authenticated (a RLS decide).
grant select on public.products, public.variants to anon;
grant select, insert, update, delete on public.products, public.variants to authenticated;

-- Pedidos: somente o admin lê pela API; alterações passam pela RPC
-- set_order_status (que ajusta o estoque). O checkout usa create_order.
-- Revogamos escrita direta para não existir caminho que burle o estoque.
revoke insert, update, delete on public.orders from anon, authenticated;
revoke insert, update, delete on public.order_items from anon, authenticated;
grant select on public.orders to authenticated;
grant select on public.order_items to authenticated;

-- A lista de admins nunca é exposta pela API; is_admin() lê como owner.
revoke all on public.admins from anon, authenticated;

-- Identities dos inserts feitos pelo admin via REST.
grant usage, select on all sequences in schema public to authenticated;

grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.create_order(text, text, text, jsonb) to anon, authenticated;
grant execute on function public.pay_order(text, text) to anon, authenticated;
grant execute on function public.order_status(text) to anon, authenticated;
grant execute on function public.set_order_status(text, text) to authenticated;

