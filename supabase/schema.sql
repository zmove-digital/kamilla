-- ----------------------------------------------------------------------------
-- Tabelas
-- ----------------------------------------------------------------------------

create table if not exists public.products (
  id               bigint generated by default as identity primary key,
  slug             text not null unique,
  name             text not null,
  category         text not null,
  subtitle         text not null default '',
  description      text not null default '',
  details          text not null default '',
  price_cents      integer not null default 0 check (price_cents >= 0),
  compare_at_cents integer check (compare_at_cents is null or compare_at_cents >= 0),
  image_url        text not null default '',
  featured         boolean not null default false,
  active           boolean not null default true,
  created_at       timestamptz not null default now()
);

create table if not exists public.variants (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  name        text not null,
  sku         text not null unique,
  price_cents integer not null default 0 check (price_cents >= 0),
  stock       integer not null default 0 check (stock >= 0),
  position    integer not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists variants_product_id_idx on public.variants(product_id);

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  number         text not null unique,
  email          text not null,
  full_name      text not null,
  address        text not null default '',
  subtotal_cents integer not null default 0,
  shipping_cents integer not null default 0,
  total_cents    integer not null default 0,
  currency       text not null default 'brl',
  status         text not null default 'pending'
                 check (status in ('pending', 'paid', 'shipped', 'cancelled', 'failed')),
  payment_provider text not null default 'mock',
  payment_ref    text,
  created_at     timestamptz not null default now(),
  paid_at        timestamptz
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);

create table if not exists public.order_items (
  id               bigint generated by default as identity primary key,
  order_id         bigint not null references public.orders(id) on delete cascade,
  variant_id       bigint references public.variants(id) on delete set null,
  product_name     text not null,
  variant_name     text not null,
  sku              text not null,
  unit_price_cents integer not null,
  quantity         integer not null check (quantity > 0)
);

create index if not exists order_items_order_id_idx on public.order_items(order_id);

-- Lista de administradores. Só o service_role (e funções security definer)
